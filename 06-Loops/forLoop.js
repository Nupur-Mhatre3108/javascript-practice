// Example 1 - Counting Forward
for (let i = 1; i <= 5; i++) {
    console.log(i);
}
/*Output:
1 
2
3
4
5
*/

// Example 2 - Counting Backward
for (let i = 5; i >= 1; i--) {
    console.log(i);
}
/* Output:
5 
4
3
2
1
*/

// Example 3 - Even Numbers
for (let i = 2; i <= 10; i += 2) {
    console.log(i);
}
/* Output:
2
4 
6
8
10
*/