let a = 5;

// Postfix Increment
console.log("a++ =", a++);//5
console.log("After a++ :", a);//6

// Prefix Increment
console.log("++a =", ++a);//7
console.log("After ++a :", a);//7

// Postfix Decrement
console.log("a-- =", a--);//7
console.log("After a-- :", a);//6

// Prefix Decrement
console.log("--a =", --a);//5
console.log("After --a :", a);//5